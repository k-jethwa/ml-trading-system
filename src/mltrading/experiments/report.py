"""Render docs/results_tables.md from results/<config>/ (no hand-copied numbers).

    python -m mltrading.experiments.report
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from mltrading.config import DEFAULT_CONFIG_PATH, PROJECT_ROOT, load_config

DOCS = PROJECT_ROOT / "docs"
MODEL_LABEL = {"mean": "mean (constant)", "reversal_5d": "reversal_5d (heuristic)", "ols": "OLS", "ridge": "Ridge",
               "hgb": "HGB (gradient-boosted trees)", "equal_weight_universe": "Equal-weight universe (long-only)"}


def md(df: pd.DataFrame, floats: int = 3) -> str:
    def fmt(v):
        if isinstance(v, float | np.floating):
            return "–" if np.isnan(v) else f"{v:.{floats}f}"
        return str(v)

    head = "| " + " | ".join(str(c) for c in df.columns) + " |\n|" + "|".join(["---"] * len(df.columns)) + "|\n"
    return head + "\n".join("| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)) + "\n"


def render(results: Path) -> str:
    out: list[str] = []
    manifest = json.loads((results / "manifest.json").read_text())
    out.append("# Results tables (generated)\n")
    out.append(f"Generated by `python -m mltrading.experiments.report` from `results/{manifest['config']['name']}/` "
               f"(run `{manifest['run_id']}`, config hash `{manifest['config_hash']}`, data fingerprint `{manifest['data_fingerprint']}`, "
               f"git `{manifest['git']['commit'][:8]}`{' + uncommitted changes' if manifest['git']['dirty'] else ''}). "
               "Development = test years 2019-2024, holdout = 2025-01-01 onward. All trading numbers are subject to the "
               "survivorship and cost caveats in `docs/limitations.md`.\n")

    ml = pd.read_csv(results / "ml_metrics.csv")
    ml["model"] = ml["model"].map(MODEL_LABEL)
    order = list(MODEL_LABEL.values())
    ml = ml.sort_values(["period", "model"], key=lambda s: s.map({m: i for i, m in enumerate(order)}) if s.name == "model" else s)
    out.append("## 1. Prediction quality (out-of-sample, walk-forward)\n")
    out.append("`rank IC` = mean per-date Spearman correlation between prediction and realized 5-day sector-relative return. "
               "`t (non-overlap)` uses every 5th date, since 5-day labels overlap. `OOS R²` = 1 − MSE / MSE of the constant predictor "
               "(negative = worse than predicting the mean); it is blank for the heuristic, whose scores are not return forecasts.\n")
    for period in ("development", "holdout", "all"):
        sub = ml[ml.period == period][["model", "n_dates", "rank_ic_mean", "rank_ic_tstat_nonoverlap", "rank_ic_hit_rate", "ic_mean", "decile_spread_5d", "oos_r2", "mae", "mse"]]
        sub = sub.rename(columns={"n_dates": "dates", "rank_ic_mean": "rank IC", "rank_ic_tstat_nonoverlap": "t (non-overlap)", "rank_ic_hit_rate": "% dates IC>0",
                                  "ic_mean": "Pearson IC", "decile_spread_5d": "top−bottom decile (5d)", "oos_r2": "OOS R²"})
        out.append(f"**{period}**\n\n{md(sub, 4)}")

    t = pd.read_csv(results / "trading_metrics.csv")
    t["strategy"] = t["model"].map(MODEL_LABEL) + " · " + t["portfolio"].str.replace("_", "-").str.replace("buy-and-hold-long-only", "buy & hold")
    out.append("## 2. Trading results (1× costs)\n")
    out.append("Net of commissions, spread, slippage and borrow. `alpha` and `beta` are from regressing daily net returns on the equal-weight "
               "universe return; `alpha t` is its t-statistic (|t| < 2 ≈ indistinguishable from zero). `turnover` = traded notional per year as a "
               "multiple of average NAV.\n")
    cols = ["strategy", "ann_return_gross", "ann_return_net", "ann_vol", "sharpe_gross", "sharpe_net", "max_drawdown", "annual_turnover",
            "annual_cost_drag", "beta_to_universe", "alpha_ann_vs_universe", "alpha_tstat"]
    ren = {"ann_return_gross": "ann ret gross", "ann_return_net": "ann ret net", "ann_vol": "ann vol", "sharpe_gross": "Sharpe gross", "sharpe_net": "Sharpe net",
           "max_drawdown": "max DD", "annual_turnover": "turnover", "annual_cost_drag": "cost drag", "beta_to_universe": "beta", "alpha_ann_vs_universe": "alpha (ann)", "alpha_tstat": "alpha t"}
    for period in ("development", "holdout", "all"):
        sub = t[(t.period == period)][cols].rename(columns=ren)
        out.append(f"**{period}**\n\n{md(sub)}")

    c = pd.read_csv(results / "cost_sensitivity.csv")
    c = c[c.period == "all"]
    c["strategy"] = c["model"].map(MODEL_LABEL) + " · " + c["portfolio"].str.replace("_", "-")
    out.append("## 3. Cost sensitivity (full test period)\n")
    out.append("Cost multiplier scales commission, spread, slippage and borrow together (1× = 5 bps/side + 50 bps/yr borrow).\n")
    out.append("Net Sharpe:\n\n" + md(c.pivot_table(index="strategy", columns="cost_multiplier", values="sharpe_net").reset_index().rename(columns=lambda x: f"{x:g}×" if isinstance(x, float) else x)))
    out.append("Net annualized return:\n\n" + md(c.pivot_table(index="strategy", columns="cost_multiplier", values="ann_return_net").reset_index().rename(columns=lambda x: f"{x:g}×" if isinstance(x, float) else x)))

    rs = pd.read_csv(results / "random_score_baseline.csv")
    out.append(f"## 4. Signal-free baseline: {len(rs)} random-score decile portfolios\n")
    out.append("Same portfolio, costs and dates, but scores are pure noise. This is what the machinery earns with no information.\n")
    summ = pd.DataFrame({
        "metric": ["net Sharpe", "gross Sharpe", "net ann return"],
        "mean": [rs.all_sharpe_net.mean(), rs.all_sharpe_gross.mean(), rs.all_ann_return_net.mean()],
        "std": [rs.all_sharpe_net.std(), rs.all_sharpe_gross.std(), rs.all_ann_return_net.std()],
        "min": [rs.all_sharpe_net.min(), rs.all_sharpe_gross.min(), rs.all_ann_return_net.min()],
        "max": [rs.all_sharpe_net.max(), rs.all_sharpe_gross.max(), rs.all_ann_return_net.max()],
    })
    out.append(md(summ))
    for m in ("ridge", "hgb"):
        row = t[(t.model == m) & (t.portfolio == "baseline") & (t.period == "all")].iloc[0]
        pct = (rs.all_sharpe_gross < row.sharpe_gross).mean() * 100
        out.append(f"* {MODEL_LABEL[m]} baseline gross Sharpe {row.sharpe_gross:.2f} beats {pct:.0f}% of the {len(rs)} random portfolios.\n")

    p = pd.read_csv(results / "parameter_sensitivity.csv")
    p = p[p.period == "all"][["model", "ann_return_net", "sharpe_gross", "sharpe_net", "annual_turnover", "beta_to_universe"]]
    out.append("## 5. Parameter sensitivity (Ridge baseline, one parameter changed at a time)\n")
    out.append("Reported for transparency, not for selection; the configured values (decile, 5-day) were fixed in advance.\n\n" + md(p.rename(columns={"model": "variant", "ann_return_net": "ann ret net", "sharpe_gross": "Sharpe gross", "sharpe_net": "Sharpe net", "annual_turnover": "turnover", "beta_to_universe": "beta"})))

    y = pd.read_csv(results / "yearly_metrics.csv")
    y["strategy"] = y["model"].map(MODEL_LABEL) + " · " + y["portfolio"].str.replace("_", "-")
    out.append("## 6. Stability by calendar year (net Sharpe; 2026 is partial, through 2026-08-17)\n")
    out.append(md(y.pivot_table(index="strategy", columns="year", values="sharpe_net").reset_index()))
    ic = pd.read_csv(results / "ic_by_year.csv")
    ic["model"] = ic["model"].map(MODEL_LABEL)
    out.append("Rank IC by year:\n\n" + md(ic.pivot_table(index="model", columns="year", values="rank_ic_mean").reset_index(), 4))

    ls = pd.read_csv(results / "label_shuffle_check.csv")
    out.append("## 7. Leakage sanity check: train on permuted labels\n")
    out.append("If the evaluation pipeline manufactured signal, models trained on shuffled labels would still show positive out-of-sample rank IC. Expected: ≈ 0.\n\n" + md(ls, 4))

    rows = []
    for m in ("ols", "ridge", "hgb"):
        lg = pd.read_csv(results / f"optimizer_log_{m}.csv")
        rows.append({"model": MODEL_LABEL[m], "rebalances": len(lg), "solved optimal": int((lg.status == "optimal").sum()),
                     "risk-check violations": int(lg.violations.sum()), "turnover limit relaxed": int(lg.get("turnover_dropped", pd.Series(dtype=bool)).fillna(False).sum()),
                     "mean gross": lg.gross.mean(), "max |net|": lg.net.abs().max(), "max |beta| (ex-ante)": lg.beta.abs().max(), "max sector net": lg.max_abs_sector_net.max()})
    out.append("## 8. Risk-aware optimizer diagnostics\n\n" + md(pd.DataFrame(rows)))

    pdist = pd.read_csv(results / "prediction_distribution.csv")
    pdist = pdist[pdist.model.isin(["ridge", "hgb"])].copy()
    pdist["model"] = pdist["model"].map(MODEL_LABEL)
    out.append("## 9. Monitoring: prediction distribution by year\n\n" + md(pdist, 5))

    timings = manifest["metrics"]["timings_sec"]
    out.append("## 10. Run timings (seconds, this run)\n\n" + md(pd.DataFrame({"stage": list(timings), "seconds": list(timings.values())}), 2))
    out.append(f"Data freshness at run time: {json.dumps(manifest['metrics']['values']['data_freshness'])}\n")
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG_PATH)
    args = parser.parse_args()
    cfg = load_config(args.config)
    path = DOCS / "results_tables.md"
    path.write_text(render(PROJECT_ROOT / "results" / cfg.name))
    print(path)


if __name__ == "__main__":
    main()
